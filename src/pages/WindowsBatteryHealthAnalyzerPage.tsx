import { useState, type ChangeEvent } from 'react';
import { Link } from 'react-router-dom';
import { SEOEngine } from '../seo/SEOEngine';
import { FaqSection } from '../components/FaqSection';
import { toolByPath } from '../data/tools';

const TOOL_PATH = '/tools/windows-battery-health-analyzer';
const MAX_REPORT_BYTES = 10 * 1024 * 1024;

type BatteryReading = {
  label: string;
  designMWh: number;
  fullMWh: number;
  cycleCount: number | null;
};

type BatteryResult = {
  batteries: BatteryReading[];
  isSample: boolean;
};

function normalizeHeader(value: string): string {
  return value.replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim().toUpperCase();
}

function readCapacity(value: string): number | null {
  const match = value.replace(/,/g, '').match(/(\d+(?:\.\d+)?)\s*(?:MWH)?/i);
  if (!match) return null;
  const parsed = Number(match[1]);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : null;
}

function readCycleCount(value: string | undefined): number | null {
  if (!value) return null;
  const normalized = value.trim();
  if (!normalized || normalized === '-' || normalized === '—' || normalized.toLowerCase() === 'n/a') return null;
  const match = normalized.replace(/,/g, '').match(/^\d+$/);
  return match ? Number(match[0]) : null;
}

function parseBatteryReport(html: string): BatteryReading[] {
  const document = new DOMParser().parseFromString(html, 'text/html');
  const bodyText = document.body?.textContent || '';
  if (!/installed batteries/i.test(bodyText)) {
    throw new Error('This does not look like a Windows battery report. Generate one with powercfg /batteryreport, save the HTML file, and select it here.');
  }

  const readings: BatteryReading[] = [];
  const tables = Array.from(document.querySelectorAll('table'));

  for (const table of tables) {
    const rows = Array.from(table.rows);
    let headerIndex = -1;
    let designIndex = -1;
    let fullIndex = -1;
    let cycleIndex = -1;

    for (let rowIndex = 0; rowIndex < rows.length; rowIndex++) {
      const cells = Array.from(rows[rowIndex].cells).map(cell => normalizeHeader(cell.textContent || ''));
      const design = cells.findIndex(cell => /DESIGN\s+CAPACITY/.test(cell));
      const full = cells.findIndex(cell => /FULL\s+CHARGE\s+CAPACITY/.test(cell));
      if (design >= 0 && full >= 0) {
        headerIndex = rowIndex;
        designIndex = design;
        fullIndex = full;
        cycleIndex = cells.findIndex(cell => /CYCLE\s+COUNT/.test(cell));
        break;
      }
    }

    if (headerIndex < 0) continue;
    for (const row of rows.slice(headerIndex + 1)) {
      const cells = Array.from(row.cells).map(cell => (cell.textContent || '').trim());
      const designMWh = readCapacity(cells[designIndex] || '');
      const fullMWh = readCapacity(cells[fullIndex] || '');
      if (!designMWh || !fullMWh) continue;
      readings.push({
        label: `Battery ${readings.length + 1}`,
        designMWh,
        fullMWh,
        cycleCount: readCycleCount(cycleIndex >= 0 ? cells[cycleIndex] : undefined),
      });
      if (readings.length >= 4) break;
    }
    if (readings.length >= 4) break;
  }

  if (!readings.length) {
    throw new Error('The file contains an Installed batteries section, but its design/full-charge capacity table could not be read. Use the original English HTML report generated by Windows, not a screenshot or a PDF printout.');
  }
  return readings;
}

function formatMWh(value: number): string {
  return `${Math.round(value).toLocaleString('en-US')} mWh`;
}

function estimateMessage(reading: BatteryReading): string {
  const ratio = (reading.fullMWh / reading.designMWh) * 100;
  if (ratio > 100.5) {
    return 'Windows reports full-charge capacity above the design figure. Battery telemetry and gauge calibration can vary; do not interpret this as proof that the battery is better than new.';
  }
  if (ratio < 80) {
    return 'The reported full-charge capacity is notably below its design figure. Compare actual runtime under similar conditions and check the laptop maker’s battery diagnostics or service criteria before deciding on replacement.';
  }
  return 'The report places full-charge capacity relatively close to the design figure. Runtime still depends on workload, display brightness, power settings, temperature, and battery age.';
}

function downloadSummary(result: BatteryResult) {
  const lines = [
    'TECH WORLD WINDOW — WINDOWS BATTERY CAPACITY REPORT',
    '===================================================',
    `Source: ${result.isSample ? 'synthetic demonstration values; not a real report' : 'Windows battery-report HTML parsed locally in this browser'}`,
    'Interpretation: capacity figures are reported by Windows/OEM software and are not a safety inspection or exact runtime prediction.',
    '',
  ];
  for (const battery of result.batteries) {
    const ratio = (battery.fullMWh / battery.designMWh) * 100;
    const loss = Math.max(0, 100 - ratio);
    lines.push(
      battery.label,
      '-'.repeat(battery.label.length),
      `Design capacity: ${formatMWh(battery.designMWh)}`,
      `Full-charge capacity: ${formatMWh(battery.fullMWh)}`,
      `Full-charge capacity versus design: ${ratio.toFixed(1)}%`,
      `Calculated capacity shortfall versus design: ${loss.toFixed(1)}%`,
      `Cycle count: ${battery.cycleCount === null ? 'Not reported' : battery.cycleCount}`,
      '',
    );
  }
  lines.push(
    'No report file or extracted battery information was uploaded by this tool.',
    'If a battery is swollen, leaking, unusually hot, damaged, or has an unusual odor, stop using it and seek qualified service. Do not open or puncture the battery pack.',
  );
  const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
  const objectUrl = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = objectUrl;
  anchor.download = `windows-battery-capacity-${new Date().toISOString().slice(0, 10)}.txt`;
  anchor.style.display = 'none';
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
}

export function WindowsBatteryHealthAnalyzerPage() {
  const tool = toolByPath.get(TOOL_PATH)!;
  const [result, setResult] = useState<BatteryResult | null>(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);

  const onFile = async (event: ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;
    setResult(null);
    setError('');
    if (file.size > MAX_REPORT_BYTES) {
      setError('This file is larger than 10 MB. Select the original Windows battery-report HTML file.');
      event.target.value = '';
      return;
    }
    setBusy(true);
    try {
      const html = await file.text();
      setResult({ batteries: parseBatteryReport(html), isSample: false });
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'The file could not be read. Select an HTML battery report generated by Windows.');
    } finally {
      setBusy(false);
      event.target.value = '';
    }
  };

  const onSample = () => {
    setError('');
    setResult({
      isSample: true,
      batteries: [{ label: 'Battery 1', designMWh: 50000, fullMWh: 41200, cycleCount: 284 }],
    });
  };

  const onClear = () => { setResult(null); setError(''); };

  return <section className="section tool-page battery-health-page">
    <SEOEngine title={tool.seoTitle} description={tool.metaDescription} path={TOOL_PATH} />
    <span className="eyebrow">FREE LOCAL ANALYSIS TOOL</span>
    <h1>Windows Battery Health Analyzer</h1>
    <p className="page-intro">Read a saved Windows battery report to compare design capacity with full-charge capacity, estimate the reported capacity shortfall, and show cycle count when Windows supplies it.</p>

    <div className="battery-privacy">
      <strong>Private by design: your report stays in this browser.</strong>
      <p>The selected HTML file is parsed locally. This tool does not upload it, send extracted battery figures to a server, or run commands on your computer.</p>
    </div>

    <div className="battery-tool-panel">
      <div className="battery-tool-actions">
        <label className="button button-primary battery-file-button">
          {busy ? 'Reading report…' : 'Choose Windows battery report (.html)'}
          <input type="file" accept=".html,.htm,text/html" onChange={onFile} disabled={busy} />
        </label>
        <button type="button" className="ft-secondary" onClick={onSample} disabled={busy}>Try sample values</button>
        {result && <button type="button" className="ft-secondary" onClick={onClear}>Clear results</button>}
      </div>
      <p className="battery-help">Supported input: the original English HTML report created by Windows with <code>powercfg /batteryreport</code>. Screenshots, PDFs, and pasted summaries are not supported yet.</p>
      <div className="battery-command">
        <strong>Create a report in Windows</strong>
        <ol>
          <li>Open Windows Terminal or Command Prompt.</li>
          <li>Run <code>powercfg /batteryreport</code>.</li>
          <li>Open the saved HTML path printed in the terminal, then choose that file above.</li>
        </ol>
      </div>
    </div>

    {error && <div className="ft-error" role="alert"><strong>Could not read this report.</strong> {error}</div>}

    {result && <div className="battery-results" aria-live="polite">
      {result.isSample && <div className="editorial-note"><strong>Synthetic example — not your battery</strong><p>These demonstration values illustrate the calculation only. Choose your own report for a result based on your device.</p></div>}
      {result.batteries.map(battery => {
        const ratio = (battery.fullMWh / battery.designMWh) * 100;
        const shortfall = Math.max(0, 100 - ratio);
        return <article className="battery-result-card" key={battery.label}>
          <div className="battery-result-heading">
            <div><span className="eyebrow">REPORTED CAPACITY</span><h2>{battery.label}</h2></div>
            <div className="battery-ratio"><strong>{ratio.toFixed(1)}%</strong><span>of design capacity</span></div>
          </div>
          <div className="battery-capacity-grid">
            <div><span>Design capacity</span><strong>{formatMWh(battery.designMWh)}</strong></div>
            <div><span>Full-charge capacity</span><strong>{formatMWh(battery.fullMWh)}</strong></div>
            <div><span>Calculated capacity shortfall</span><strong>{shortfall.toFixed(1)}%</strong></div>
            <div><span>Cycle count</span><strong>{battery.cycleCount === null ? 'Not reported' : battery.cycleCount.toLocaleString('en-US')}</strong></div>
          </div>
          <p className="battery-interpretation">{estimateMessage(battery)}</p>
        </article>;
      })}
      <p className="ft-input-actions"><button type="button" className="ft-secondary" onClick={() => downloadSummary(result)}>Download summary (.txt)</button><button type="button" className="ft-secondary" onClick={onClear}>Clear results</button></p>
      <p className="battery-disclaimer">The capacity ratio is an estimate from reported values, not a manufacturer-certified health verdict. It cannot predict exact battery runtime, diagnose individual cells, or prove the battery is safe.</p>
    </div>}

    <div className="article-body battery-explain">
      <section>
        <h2>How the calculation works</h2>
        <p>Windows reports Design Capacity and Full Charge Capacity for batteries that expose those values. This tool calculates Full Charge Capacity divided by Design Capacity, multiplied by 100. A lower ratio means the report currently shows less available capacity than the original design figure.</p>
        <p>Some reports omit cycle count or other fields. Missing values are shown as unavailable rather than estimated. If Full Charge Capacity is above Design Capacity, reporting or calibration variation may explain it; the tool does not calculate negative wear.</p>
      </section>
      <section>
        <h2>What this result cannot tell you</h2>
        <p>Capacity is not the same as remaining runtime. Background workloads, brightness, sleep behavior, temperature, battery calibration and the laptop’s power profile can change how long it runs. Compare runtime under similar conditions and check the device maker’s own diagnostic guidance before ordering a replacement.</p>
      </section>
      <section className="battery-safety-note">
        <h2>Battery safety comes first</h2>
        <p>A low capacity figure alone does not mean a battery is dangerous. Swelling, leaking, physical damage, unusual heat, or a chemical odor are separate warning signs. Stop using a visibly swollen or damaged battery, do not charge or press on it, and arrange qualified service. Never puncture or open a battery pack.</p>
      </section>
      <section>
        <h2>Related guides and tools</h2>
        <ul>
          <li><Link className="text-link" to="/laptop-battery-warning-signs">Laptop battery warning signs: swelling, heat and sudden shutdowns</Link></li>
          <li><Link className="text-link" to="/tools/windows-troubleshooting-assistant">Windows Troubleshooting Assistant</Link></li>
        </ul>
      </section>
    </div>
    <FaqSection items={tool.faq || []} />
  </section>;
}
