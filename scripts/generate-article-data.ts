import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { articles, categories, type Article } from '../src/data/articles';
import { routeGraph } from '../src/data/graph';

const root = process.cwd();
const generatedRoot = path.resolve(root, 'src/data/generated');
const contentRoot = path.join(generatedRoot, 'article-content');

function contentFileName(slug: string): string {
  // Public article slugs use lowercase words and hyphens. Double hyphens make
  // nested public paths unambiguous in a flat generated directory.
  return `${slug.replace(/\//g, '--')}.json`;
}

const ids = new Set<string>();
const slugs = new Set<string>();
const fileNames = new Set<string>();

for (const article of articles) {
  if (ids.has(article.id)) throw new Error(`Duplicate article ID: ${article.id}`);
  if (slugs.has(article.slug)) throw new Error(`Duplicate article slug: ${article.slug}`);
  const fileName = contentFileName(article.slug);
  if (fileNames.has(fileName)) throw new Error(`Article content filename collision: ${fileName}`);
  ids.add(article.id);
  slugs.add(article.slug);
  fileNames.add(fileName);
}

const articleRoutes = routeGraph.filter(route => route.kind === 'article');
const missingRoutes = articleRoutes.filter(route => !slugs.has(route.path.replace(/^\//, '')));
if (missingRoutes.length) {
  throw new Error(`Article routes missing content data: ${missingRoutes.map(route => route.path).join(', ')}`);
}

const summaries = articles.map(article => {
  const summary = { ...article, content: [] as Article['content'] };
  delete summary.sources;
  delete summary.testing;
  delete summary.faq;
  delete summary.howTo;
  return summary;
});

await mkdir(contentRoot, { recursive: true });
const existing = await readdir(contentRoot);
const wanted = new Set(articles.map(article => contentFileName(article.slug)));
for (const name of existing) {
  if (name.endsWith('.json') && !wanted.has(name)) {
    await rm(path.join(contentRoot, name), { force: true });
  }
}

for (const article of articles) {
  await writeFile(
    path.join(contentRoot, contentFileName(article.slug)),
    JSON.stringify(article),
    'utf8',
  );
}

const indexSource = [
  '// Generated by scripts/generate-article-data.ts. Do not edit this file directly.',
  "import type { Article } from './articles';",
  '',
  `export const articles: Article[] = ${JSON.stringify(summaries)};`,
  '',
  `export const categories = ${JSON.stringify(categories)};`,
  '',
].join('\n');

await writeFile(path.join(generatedRoot, 'article-index.ts'), indexSource, 'utf8');

console.log(
  `Generated a lightweight index for ${articles.length} articles and ${articleRoutes.length} article routes; ${articles.length} route-specific content modules ready.`,
);
